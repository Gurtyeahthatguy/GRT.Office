const encoder = new TextEncoder();

/** A package from named texts and bytes, as readPackage gives it. */
function pkg(files) {
  const entries = new Map(Object.entries(files).map(([name, data]) => [name, typeof data === 'string' ? encoder.encode(data) : data]));
  return decodeBlock(encodeBlock([...entries].map(([name, data]) => ({ name, data }))));
}

const CONTENT = (url) => `<?xml version="1.0" encoding="UTF-8"?><office:document-content xmlns:office="urn:oasis:names:tc:opendocument:xmlns:office:1.0" xmlns:db="urn:oasis:names:tc:opendocument:xmlns:database:1.0" xmlns:xlink="http://www.w3.org/1999/xlink"><office:body><office:database><db:data-source><db:connection-data><db:connection-resource xlink:href="${url}"/></db:connection-data></db:data-source><db:queries><db:query db:name="cheap" db:command="SELECT * FROM &quot;items&quot; WHERE &quot;price&quot; &lt; 2"/></db:queries></office:database></office:body></office:document-content>`;

describe('an HSQLDB script', () => {
  it('reads MEMORY tables with their rows, escapes, keys and identity', () => {
    const script = [
      'SET DATABASE COLLATION "Italian"',
      'CREATE SCHEMA PUBLIC AUTHORIZATION DBA',
      'CREATE MEMORY TABLE "regions"("id" INTEGER GENERATED BY DEFAULT AS IDENTITY(START WITH 0) NOT NULL PRIMARY KEY,"name" VARCHAR(40) NOT NULL)',
      'CREATE MEMORY TABLE "items"("id" INTEGER NOT NULL PRIMARY KEY,"name" VARCHAR(50),"price" DECIMAL(8,2),"ok" BOOLEAN,"born" DATE,"region" INTEGER,"bin" VARBINARY(4),CONSTRAINT "fk" FOREIGN KEY("region") REFERENCES "regions"("id") ON DELETE CASCADE)',
      'CREATE UNIQUE INDEX "by_name" ON "items"("name")',
      'ALTER TABLE "regions" ALTER COLUMN "id" RESTART WITH 2',
      'SET SCHEMA PUBLIC',
      "INSERT INTO \"regions\" VALUES(0,'Nord')",
      "INSERT INTO \"regions\" VALUES(1,'Sud')",
      "INSERT INTO \"items\" VALUES(1,'Citt\\u00e0 ''vecchia''',1.50,TRUE,'1990-04-05',0,'0100ff07')",
      'INSERT INTO "items" VALUES(2,NULL,-3.25,FALSE,NULL,1,NULL)',
    ].join('\n');
    const database = readOdb(pkg({ 'content.xml': CONTENT('sdbc:embedded:hsqldb'), 'database/script': script, 'database/properties': 'hsqldb.script_format=0\n' }));
    const [regions, items] = database.tables;
    expect(regions.columns[0]).toMatchObject({ name: 'id', autoIncrement: true, next: 2 });
    expect(regions.rows).toEqual([[0, 'Nord'], [1, 'Sud']]);
    expect(items.rows[0]).toEqual([1, "Città 'vecchia'", 1.5, 1, '1990-04-05', 0, new Uint8Array([1, 0, 255, 7])]);
    expect(items.rows[1]).toEqual([2, null, -3.25, 0, null, 1, null]);
    expect(items.foreignKeys).toEqual([{ name: 'fk', columns: ['region'], table: 'regions', toColumns: ['id'], onDelete: 'CASCADE' }]);
    expect(items.indexes).toEqual([{ name: 'by_name', columns: ['name'], unique: true }]);
    expect(database.queries).toEqual([{ name: 'cheap', sql: 'SELECT * FROM "items" WHERE "price" < 2' }]);
  });

  it('becomes SQLite that GRT writes itself: names quoted, values as literals, the counter kept', () => {
    const database = {
      tables: [{ name: 'a"b', columns: [{ name: 'id', kind: 'INTEGER', declared: 'INTEGER', autoIncrement: true, next: 5 }, { name: 'x; DROP', kind: 'VARCHAR', declared: 'VARCHAR(5)' }], primaryKey: ['id'], foreignKeys: [], indexes: [], rows: [[1, "it's"], [2, new Uint8Array([255])]] }],
    };
    const { schema, data } = sqliteImport(database);
    expect(schema).toContain('CREATE TABLE "a""b" (\n  "id" INTEGER PRIMARY KEY AUTOINCREMENT,\n  "x; DROP" VARCHAR(5)\n);');
    expect(data).toContain(`INSERT INTO "a""b" ("id", "x; DROP") VALUES (1, 'it''s');`);
    expect(data).toContain("VALUES (2, X'ff');");
    expect(data).toContain(`INSERT OR REPLACE INTO sqlite_sequence (name, seq) VALUES ('a"b', 4);`);
  });

  it('is written back so that it reads the same', () => {
    const tables = [
      { name: 'regions', columns: [{ name: 'id', declared: 'INTEGER', autoIncrement: true, notNull: true }, { name: 'name', declared: 'TEXT' }], primaryKey: ['id'], foreignKeys: [], indexes: [], rows: [[1, 'Nörd']] },
      { name: 'items', columns: [{ name: 'id', declared: 'INTEGER' }, { name: 'price', declared: 'NUMERIC(8,2)' }, { name: 'when', declared: 'TIMESTAMP' }, { name: 'ok', declared: 'BOOLEAN' }, { name: 'region', declared: 'INTEGER' }],
        primaryKey: ['id'], foreignKeys: [{ columns: ['region'], table: 'regions', toColumns: ['id'] }], indexes: [{ name: 'by_price', columns: ['price'], unique: false }], rows: [[1, 2.5, '2020-01-02 03:04:05', 1, 1]] },
    ];
    const entries = writeOdb({ tables, queries: [{ name: 'all', sql: 'SELECT 1' }] });
    expect(entries[0]).toMatchObject({ name: 'mimetype', store: true });
    const script = entries.find((e) => e.name === 'database/script').data;
    expect(script).toContain('CREATE MEMORY TABLE "regions"("id" INTEGER GENERATED BY DEFAULT AS IDENTITY(START WITH 0) NOT NULL PRIMARY KEY,"name" LONGVARCHAR)');
    expect(script).toContain("INSERT INTO \"regions\" VALUES(1,'N\\u00f6rd')");
    expect(script).toContain('ALTER TABLE "regions" ALTER COLUMN "id" RESTART WITH 2');
    const again = readOdb(pkg(Object.fromEntries(entries.map((e) => [e.name, e.data]))));
    expect(again.tables.map((t) => t.rows)).toEqual([[[1, 'Nörd']], [[1, 2.5, '2020-01-02 03:04:05', 1, 1]]]);
    expect(again.tables[1].foreignKeys[0]).toMatchObject({ columns: ['region'], table: 'regions' });
    expect(again.queries).toEqual([{ name: 'all', sql: 'SELECT 1' }]);
  });

  it('names types HSQLDB knows, by what the column holds', () => {
    expect(hsqlTypeOf('TEXT')).toBe('LONGVARCHAR');
    expect(hsqlTypeOf('VARCHAR(20)')).toBe('VARCHAR(20)');
    expect(hsqlTypeOf('INTEGER', [5_000_000_000])).toBe('BIGINT');
    expect(hsqlTypeOf('REAL')).toBe('DOUBLE');
    expect(hsqlTypeOf('BLOB')).toBe('LONGVARBINARY');
    expect(hsqlTypeOf('DATE')).toBe('DATE');
    expect(hsqlTypeOf('')).toBe('LONGVARCHAR');
  });
});

describe('forms and reports inside a .odb', () => {
  it('are read back for the table they show and how', () => {
    const columns = [{ name: 'id', declared: 'INTEGER' }, { name: 'name', declared: 'TEXT' }, { name: 'region', declared: 'INTEGER' }];
    const tables = [{ name: 'items', columns, primaryKey: ['id'], foreignKeys: [], indexes: [], rows: [] }];
    const forms = [odbForm({ name: 'Edit items', table: 'items', fields: ['name', 'region'] }, columns, 0)];
    const reports = [odbReport({ name: 'By region', table: 'items', groupBy: 'region', columns: ['name'] }, columns, 0)];
    const entries = writeOdb({ tables, queries: [] }, { forms, reports });
    const manifest = entries.find((e) => e.name === 'META-INF/manifest.xml').data;
    expect(manifest).toContain('manifest:full-path="forms/Obj11/" manifest:version="1.3"');
    expect(manifest).toContain('manifest:full-path="reports/Obj11/" manifest:media-type="application/vnd.sun.xml.report"');
    const again = readOdb(pkg(Object.fromEntries(entries.map((e) => [e.name, e.data]))));
    expect(again.forms).toEqual([{ name: 'Edit items', table: 'items', commandType: 'table', fields: ['name', 'region'] }]);
    expect(again.reports).toEqual([{ name: 'By region', table: 'items', commandType: 'table', groupBy: 'region', columns: ['name'] }]);
  });
});

describe('a hostile .odb', () => {
  const script = 'CREATE CACHED TABLE "t"("id" INTEGER NOT NULL PRIMARY KEY)\nSET TABLE "t" INDEX\'32 0\'';
  const open = (data) => readOdb(pkg({ 'content.xml': CONTENT('sdbc:embedded:hsqldb'), 'database/script': script, 'database/data': data }));

  it('reports a row index that loops instead of following it for ever', () => {
    const data = new Uint8Array(80);
    const view = new DataView(data.buffer);
    view.setInt32(32, 48);
    view.setInt32(32 + 12, 32);
    view.setUint8(52, 1);
    view.setInt32(53, 7);
    const database = open(data);
    expect(database.losses.join()).toMatch(/loops/);
  });

  it('reports a row that points outside the file', () => {
    const data = new Uint8Array(64);
    new DataView(data.buffer).setInt32(32 + 12, 1 << 30);
    expect(open(data).losses.join()).toMatch(/outside the file/);
  });

  it('refuses a database that lives on a server', () => {
    expect(() => readOdb(pkg({ 'content.xml': CONTENT('sdbc:mysql:jdbc:example.org:3306/db') }))).toThrow(/server/);
  });

  it('refuses a Firebird backup that is cut short', () => {
    const backup = new Uint8Array([0, 2, 4, 11, 0, 0, 0, 0, 3, 1, 6]);
    expect(() => readOdb(pkg({ 'content.xml': CONTENT('sdbc:embedded:firebird'), 'database/firebird.fbk': backup }))).toThrow();
  });
});

describe('what Base keeps beside the tables', () => {
  const schema = {
    name: 'items', sql: 'CREATE TABLE items (id INTEGER PRIMARY KEY, name TEXT, region INTEGER REFERENCES regions(id))',
    columns: [{ name: 'id', type: 'INTEGER', primaryKey: true, notNull: false }, { name: 'name', type: 'TEXT' }, { name: 'region', type: 'INTEGER' }],
    foreignKeys: [{ column: 'region', table: 'regions', toColumn: 'id', onDelete: 'NO ACTION' }],
    indexes: [{ name: 'sqlite_autoindex', origin: 'u', unique: true, columns: ['name'] }],
  };

  it('turns a table and its rows, files as hex, into what the writer takes', () => {
    const model = tableModel(schema, { rows: [[1, 'a', null], [2, { hex: '00ff' }, 1]] });
    expect(model.columns[0]).toMatchObject({ name: 'id', autoIncrement: true });
    expect(model.rows[1][1]).toEqual(new Uint8Array([0, 255]));
    expect(model.indexes).toEqual([{ name: null, columns: ['name'], unique: true }]);
    expect(inKeyOrder([model, { name: 'regions', foreignKeys: [] }]).map((t) => t.name)).toEqual(['regions', 'items']);
  });

  it('writes a form as a document with a control for each field', () => {
    const form = odbForm({ name: 'Items', table: 'items', fields: ['name', 'region'] }, tableModel(schema, { rows: [] }).columns, 0);
    const content = form.files[0][1];
    expect(form.href).toBe('forms/Obj11');
    expect(content).toContain('form:command="items" form:command-type="table"');
    expect(content).toContain('form:data-field="name"');
    expect(content).toContain('form:formatted-text');
    expect(content).not.toContain('form:data-field="id"');
  });

  it('keeps queries, views, forms and reports read from a .odb, for tables that are there', () => {
    const objects = objectsFromOdb({
      tables: [{ name: 'items' }], queries: [{ name: 'q', sql: 'SELECT 1' }], views: [{ name: 'v', sql: 'SELECT 2' }],
      forms: [{ name: 'f', table: 'items', fields: ['name'] }, { name: 'gone', table: 'nowhere', fields: [] }],
      reports: [{ name: 'r', table: 'items', groupBy: 'region' }],
    });
    expect(objects.map((o) => `${o.kind}:${o.name}`)).toEqual(['query:q', 'query:v', 'form:f', 'report:r']);
  });

  it('writes a report as a text document with its groups, totals and chart', () => {
    const definition = { groupBy: 'region', totals: { qty: 'sum' }, chart: true, title: 'Sales' };
    const report = buildReport(definition, ['item', 'qty', 'region'], [['Pen', 3, 'North'], ['Ink', 1, 'South'], ['Clip', 5, 'South']]);
    const document = reportDocument(report, definition);
    expect(document.blocks.map((b) => b.kind)).toEqual(['heading', 'chart', 'heading', 'table', 'heading', 'table', 'table']);
    const { entries } = writeOdt(document);
    const content = new TextDecoder().decode(entries.find((e) => e.name === 'content.xml').data instanceof Uint8Array ? entries.find((e) => e.name === 'content.xml').data : encoder.encode(entries.find((e) => e.name === 'content.xml').data));
    expect(content).toContain('region: South');
    expect(content).toContain('Sum 6');
  });
});

// LibreOffice as the oracle: it makes .odb files with each engine, and reads back what GRT writes.

const uno = spawnSync('python3', ['-c', 'import uno']).status === 0 && oracleAvailable();

function makeOdb(dir, engine, spec) {
  const file = join(dir, `${engine}.odb`);
  writeFileSync(join(dir, 'spec.json'), JSON.stringify(spec));
  execFileSync('python3', [baseScript, 'make', file, engine, join(dir, 'spec.json')], { timeout: 180000, stdio: 'pipe' });
  return file;
}
const dumpOdb = (file) => JSON.parse(execFileSync('python3', [baseScript, 'dump', file], { timeout: 180000, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }));
const readFile = (file) => readOdb(decodeBlock(readBlock(file)));

const SPEC = (engine) => ({
  sql: [
    `CREATE TABLE "regions" ("id" INTEGER GENERATED BY DEFAULT AS IDENTITY${engine === 'hsqldb' ? '(START WITH 0)' : ''} PRIMARY KEY, "name" VARCHAR(40) NOT NULL)`,
    `CREATE TABLE "items" ("id" INTEGER PRIMARY KEY, "name" VARCHAR(50), "price" DECIMAL(8,2), "ok" BOOLEAN, "born" DATE, "at" TIME, "stamp" TIMESTAMP, "big" BIGINT, "memo" ${engine === 'hsqldb' ? 'LONGVARCHAR' : 'BLOB SUB_TYPE TEXT'}, "region" INTEGER, CONSTRAINT "fk_region" FOREIGN KEY ("region") REFERENCES "regions" ("id"))`,
    'CREATE INDEX "by_name" ON "items" ("name")',
    `INSERT INTO "regions" ("name") VALUES ('Nord')`,
    `INSERT INTO "regions" ("name") VALUES ('Città')`,
    `INSERT INTO "items" VALUES (1, 'Ann O''Neil', 12.50, TRUE, '1990-04-05', '13:30:15', '2020-02-02 08:05:09', 1000000000000, 'a long note', ${engine === 'hsqldb' ? 0 : 1})`,
    `INSERT INTO "items" VALUES (2, 'Bruno', -3.25, FALSE, NULL, NULL, NULL, -5, NULL, ${engine === 'hsqldb' ? 1 : 2})`,
  ],
  queries: { 'cheap items': 'SELECT "name" FROM "items" WHERE "price" < 5' },
});

describe.skipIf(!uno)('LibreOffice Base as the oracle', () => {
  for (const engine of ['hsqldb', 'firebird']) {
    it(`reads what LibreOffice writes with ${engine}`, () => {
      const dir = scratch();
      try {
        const database = readFile(makeOdb(dir, engine, SPEC(engine)));
        const items = database.tables.find((t) => t.name === 'items');
        const regions = database.tables.find((t) => t.name === 'regions');
        expect(regions.rows.map((r) => r[1])).toEqual(['Nord', 'Città']);
        expect(items.rows[0]).toEqual([1, "Ann O'Neil", 12.5, 1, '1990-04-05', '13:30:15', '2020-02-02 08:05:09', 1000000000000, 'a long note', regions.rows[0][0]]);
        expect(items.rows[1]).toEqual([2, 'Bruno', -3.25, 0, null, null, null, -5, null, regions.rows[1][0]]);
        expect(items.foreignKeys[0]).toMatchObject({ columns: ['region'], table: 'regions', toColumns: ['id'] });
        expect(items.indexes.map((i) => i.columns)).toContainEqual(['name']);
        expect(regions.columns[0].autoIncrement).toBe(true);
        expect(database.queries).toEqual([{ name: 'cheap items', sql: 'SELECT "name" FROM "items" WHERE "price" < 5' }]);
        expect(database.losses).toEqual([]);
      } finally {
        cleanup(dir);
      }
    }, 240000);
  }

  it('writes what LibreOffice opens, with the same values, queries and forms', () => {
    const dir = scratch();
    try {
      const database = readFile(makeOdb(dir, 'firebird', SPEC('firebird')));
      const columns = database.tables.find((t) => t.name === 'items').columns;
      const forms = [odbForm({ name: 'Items', table: 'items', fields: [] }, columns, 0)];
      const reports = [odbReport({ name: 'By region', table: 'items', title: 'Items by region', groupBy: 'region', columns: ['name', 'price'] }, columns, 0)];
      const out = join(dir, 'back.odb');
      writeBlock(encodeBlock(writeOdb({ tables: inKeyOrder(database.tables), queries: database.queries }, { forms, reports })), out);
      const seen = dumpOdb(out);
      expect(seen.tables.items.rows[0]).toEqual(['1', "Ann O'Neil", '12.50', 'true', '1990-04-05', '13:30:15', '2020-02-02 08:05:09.000000000', '1000000000000', 'a long note', '1']);
      expect(seen.tables.regions.rows).toEqual([['1', 'Nord'], ['2', 'Città']]);
      expect(seen.queries).toEqual({ 'cheap items': 'SELECT "name" FROM "items" WHERE "price" < 5' });
      expect(seen.forms).toEqual(['Items']);
      expect(seen.reports).toEqual(['By region']);
      // LibreOffice runs the report: a group for each region, the labels, then the rows.
      expect(seen.reportOutputs['By region']).toMatch(/^1\t\nname\tprice\nAnn O'Neil\t12[.,]5\n2\t\nname\tprice\nBruno\t-3[.,]25\n/);
      expect(seen.formControls.Items).toEqual({ command: 'items', fields: ['id', 'name', 'price', 'ok', 'born', 'at', 'stamp', 'big', 'memo', 'region'] });
    } finally {
      cleanup(dir);
    }
  }, 240000);
});
